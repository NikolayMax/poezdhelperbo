export class ErrorService {
     serverError(additionalInfo?: string): string {
        return `🛠️ Произошла ошибка сервера

Приносим извинения за неудобства! Наша команда уже уведомлена о проблеме и работает над её решением.

${additionalInfo ? `📋 Дополнительная информация: ${additionalInfo}\n` : ''}🕒 Попробуйте повторить запрос через несколько минут

Если проблема сохраняется, обратитесь в поддержку.`;
    }

    timeoutError(): string {
        return `⏰ Превышено время ожидания

Сервер не ответил вовремя. Возможно, высокая нагрузка или проблемы с соединением.

🔁 Пожалуйста, попробуйте еще раз через минуту`;
    }

    /**
     * Ошибка базы данных
     */
     databaseError(): string {
        return `🗄️ Ошибка базы данных

Не удалось получить или сохранить данные. Мы уже знаем о проблеме и исправляем её.

📊 Попробуйте повторить действие через некоторое время`;
    }

    /**
     * Ошибка соединения с внешним сервисом
     */
     externalServiceError(serviceName: string): string {
        return `🌐 Ошибка соединения с ${serviceName}

В настоящее время сервис временно недоступен. Мы уже работаем над восстановлением.

🔄 Автоматически повторим попытку через 5 минут`;
    }

    /**
     * Ошибка валидации данных
     */
     validationError(field?: string): string {
        return `📝 Ошибка в данных${field ? ` поля "${field}"` : ''}

Проверьте правильность введенной информации и попробуйте еще раз.

💡 Подсказка: убедитесь, что все обязательные поля заполнены корректно`;
    }

    /**
     * Ошибка "Не найдено"
     */
     notFoundError(resource: string): string {
        return `🔍 ${resource} не найден(а)

Запрошенная информация временно недоступна или была удалена.

📂 Попробуйте уточнить критерии поиска`;
    }

    /**
     * Общая ошибка с кастомным сообщением
     */
     customError(message: string, emoji: string = '❌'): string {
        return `${emoji} ${message}

Если проблема повторяется, обратитесь в техническую поддержку.`;
    }
}